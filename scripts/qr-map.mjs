#!/usr/bin/env node
// Writes api/_qr-map.js: the fallback inventory-number -> slug map the /qr/
// redirect uses when Artfolio's catalogue API can't be reached.
//
//   node scripts/qr-map.mjs            (reads catalogue_v1, like the snapshot)
//
// Runs before every build (npm run build). If the API is down the committed
// file is kept.
import { writeFile } from "node:fs/promises";
import { mapFromCatalogue } from "../api/qr.js";

const SUPABASE_URL = process.env.SUPABASE_URL || "https://trcqmiemvyoxeetgfguo.supabase.co";
const ANON_KEY = process.env.SUPABASE_ANON_KEY || "sb_publishable_UG-NEwH8e6-YNrKIcOY1vw_dydhBKDg";
const ARTIST = process.env.ARTIST_SLUG || "xano-armenter";

const res = await fetch(`${SUPABASE_URL}/rest/v1/rpc/catalogue_v1`, {
  method: "POST",
  headers: { apikey: ANON_KEY, "Content-Type": "application/json" },
  body: JSON.stringify({ p_artist_slug: ARTIST }),
  signal: AbortSignal.timeout(60_000),
});
if (!res.ok) throw new Error(`catalogue_v1 answered HTTP ${res.status}`);
const works = mapFromCatalogue(await res.json());
const n = Object.keys(works).length;
if (n === 0) throw new Error("catalogue_v1 returned no works with images; keeping the committed map");
const sorted = Object.fromEntries(Object.entries(works).sort(([a], [b]) => a.localeCompare(b)));
await writeFile(
  new URL("../api/_qr-map.js", import.meta.url),
  `// Generated by scripts/qr-map.mjs. Fallback for api/qr.js when Artfolio is unreachable.\n` +
    `export default ${JSON.stringify({ generated_at: new Date().toISOString(), works: sorted }, null, 2)};\n`,
);
console.log(`qr-map: ${n} works -> api/_qr-map.js`);
