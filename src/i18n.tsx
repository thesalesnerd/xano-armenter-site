const strings = { en, es };

export function langFromPath(pathname: string): Lang {
  return pathname === "/es" || pathname.startsWith("/es/") ? "es" : "en";
}

/** Strings for the current language, plus helpers for language-aware links. */
export function useI18n() {
  const { pathname, search } = useLocation();
  const lang = langFromPath(pathname);
  const bare = lang === "es" ? pathname.slice(3) || "/" : pathname;
  return {
    lang,
    t: strings[lang],
    /** Prefix an app path ("/work") for the current language. */
    to: (path: string) => (lang === "es" ? `/es${path === "/" ? "" : path}` : path),
    /** The current page in the other language. */
    switchTo: (lang === "es" ? bare : `/es${bare === "/" ? "" : bare}`) + search,
    medium: (m: string | null) => (m ? strings[lang].medium[m] ?? m : ""),
  };
}
