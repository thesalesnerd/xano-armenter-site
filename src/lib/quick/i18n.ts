export function defaultLang(): Lang {
  const nav = (typeof navigator !== 'undefined' ? navigator.language : 'es').toLowerCase();
  if (nav.startsWith('ca')) return 'ca';
  if (nav.startsWith('en')) return 'en';
  return 'es';
}
